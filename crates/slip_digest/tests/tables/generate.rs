//! The generator of `src/tables.rs`, of `tests/tables/extra.rs` and of
//! `tests/tables/pins.txt` (WP-023).

use std::collections::BTreeSet;
use std::fmt::Write as _;

use super::kiln::Descs;
use super::{Doc, Encoding, Kind, Number, Pin, Type, screaming, snake};

/// Kiln's private modules whose types it re-exports one level up: a type
/// named `<private>::X` by its descriptor is named `<public>::X` from
/// outside. A wrong entry does not compile. A type at a private path that
/// is not re-exported is listed in `pins.txt` instead.
const REEXPORTS: &[(&str, &str)] = &[
    ("kiln::ast::types::context::", "kiln::ast::types::"),
    ("kiln::ast::types::func::", "kiln::ast::types::"),
    ("kiln::ast::types::kinds::", "kiln::ast::types::"),
    ("kiln::ast::types::layout::", "kiln::ast::types::"),
    ("kiln::ast::types::names::", "kiln::ast::types::"),
    ("kiln::ast::types::nns::", "kiln::ast::types::"),
    ("kiln::ast::consts::value::", "kiln::ast::consts::"),
    ("kiln::source::loc::", "kiln::source::"),
];

/// A type name as `std::any::type_name` writes it, as Slip code names it:
/// through `slip_kiln::kiln` and Kiln's re-exports, `alloc`/`core` as
/// `std`.
pub fn rust_type(name: &str) -> String {
    let mut out = String::new();
    let mut path = String::new();
    let flush = |path: &mut String, out: &mut String| {
        if !path.is_empty() {
            out.push_str(&rust_path(path));
            path.clear();
        }
    };
    for c in name.chars() {
        if c.is_ascii_alphanumeric() || c == '_' || c == ':' {
            path.push(c);
        } else {
            flush(&mut path, &mut out);
            out.push(c);
        }
    }
    flush(&mut path, &mut out);
    out
}

fn rust_path(p: &str) -> String {
    let mut s = if let Some(r) = p.strip_prefix("kiln_") {
        format!("kiln::{r}")
    } else if let Some(r) = p.strip_prefix("alloc::").or_else(|| p.strip_prefix("core::")) {
        format!("std::{r}")
    } else {
        return p.to_owned();
    };
    // The prelude's names, unqualified (`unused_qualifications`).
    for (full, bare) in [
        ("std::boxed::Box", "Box"),
        ("std::vec::Vec", "Vec"),
        ("std::string::String", "String"),
        ("std::option::Option", "Option"),
        ("std::result::Result", "Result"),
    ] {
        if s == full {
            return bare.to_owned();
        }
    }
    for (private, public) in REEXPORTS {
        if let Some(r) = s.strip_prefix(private)
            && !r.contains("::")
        {
            s = format!("{public}{r}");
            break;
        }
    }
    s
}

/// `0x` and 16 hexadecimal digits in groups of four.
fn hex(h: u64) -> String {
    let d = format!("{h:016x}");
    format!("0x{}_{}_{}_{}", &d[0..4], &d[4..8], &d[8..12], &d[12..16])
}

/// A module name: the short name in snake case, raw if a keyword.
fn module(short: &str) -> String {
    const KEYWORDS: &[&str] = &[
        "as", "async", "await", "box", "break", "const", "continue", "dyn", "else", "enum",
        "extern", "false", "fn", "for", "gen", "if", "impl", "in", "let", "loop", "macro", "match",
        "mod", "move", "mut", "priv", "pub", "ref", "return", "static", "struct", "trait", "true",
        "try", "type", "unsafe", "use", "where", "while", "yield",
    ];
    let s = snake(short);
    if KEYWORDS.contains(&s.as_str()) { format!("r#{s}") } else { s }
}

/// The instantiations of the pinned types: `(type, descriptor name, hash)`
/// in table order, each type's instantiations sorted.
pub fn pinned<'d>(doc: &'d Doc, descs: &'d Descs) -> Vec<(&'d Type, &'d str, Option<u64>)> {
    let mut out = vec![];
    for t in doc.types.iter().filter(|t| t.pin != Pin::None) {
        for d in descs.of(&t.path) {
            out.push((t, d.name.as_str(), d.hash));
        }
    }
    out
}

const HEADER: &str = "\
// @generated by `crates/slip_digest/tests/tables.rs` (WP-023): do not edit.
//
// From `spec/digest-kinds.md` and the schema descriptors of the Kiln that
// `slip_kiln` links (the `kiln` submodule). After changing either, run
// `SLIP_BLESS=1 cargo test -p slip_digest --test tables` and review the diff.
// When a pin below no longer compiles (the Kiln pin moved), add
// `--features unpinned` to that command: the feature leaves the pins out
// and exists for nothing else.
";

/// `src/tables.rs`. `unnameable` holds the descriptor names of the pinned
/// types Slip cannot name (`pins.txt`). Errors are what cannot be
/// generated.
pub fn tables_rs(
    doc: &Doc,
    descs: &Descs,
    unnameable: &BTreeSet<String>,
) -> Result<String, Vec<String>> {
    let mut o = String::from(HEADER);
    let mut errors = vec![];
    o.push_str(
        "\n//! The digest's tables (`spec/digest-kinds.md`) as Rust: every tag and\n\
         //! decision, Slip's own numbers of §1.7, §3.1, §3.2 and §11.1, and the\n\
         //! schema pins (`spec/digest.md` §13 obligation 3).\n\n\
         #![allow(dead_code, clippy::too_many_lines, clippy::trivially_copy_pass_by_ref)]\n\n\
         use slip_kiln::kiln;\n\
         #[cfg(not(feature = \"unpinned\"))]\n\
         use kiln::snap::Snap;\n\n\
         /// The Decision column (`spec/digest-kinds.md` §1.2).\n\
         #[derive(Clone, Copy, Debug, PartialEq, Eq)]\n\
         pub(crate) enum Decision {\n    In,\n    Out,\n    Symbolic,\n    Demand,\n    Unsupported,\n}\n\n\
         /// One variant row: its number (§1.4; for `as V`, V's number) and decision.\n\
         #[derive(Clone, Copy, Debug, PartialEq, Eq)]\n\
         pub(crate) struct Row {\n    pub tag: u32,\n    pub decision: Decision,\n}\n",
    );
    let mut modules = BTreeSet::new();
    for (m, title, list) in [
        ("key_kind", "§3.1 `KeyKind`", &doc.key_kinds),
        ("name", "§3.2 `Name`", &doc.names),
        ("property", "§11.1 the resolved properties", &doc.properties),
        ("walk_row", "§1.7 the rows of the walk", &doc.walk),
    ] {
        modules.insert(m.to_owned());
        numbers(&mut o, m, title, list, &mut errors);
    }
    for t in &doc.types {
        let m = module(&t.short);
        if !modules.insert(m.clone()) {
            errors.push(format!("{}: module `{m}` is generated twice", t.path));
        }
        let _ = write!(o, "\n/// `{}`.\npub(crate) mod {m} {{\n", t.path);
        if t.has_variants() {
            variant_module(&mut o, t, descs, unnameable, &mut errors);
        } else {
            o.push_str(
                "    use super::Decision;\n\n    pub(crate) const ROWS: &[(&str, Decision)] = &[\n",
            );
            for r in &t.rows {
                let _ = writeln!(o, "        ({:?}, Decision::{}),", r.text, r.decision.rust());
            }
            o.push_str("    ];\n");
        }
        o.push_str("}\n");
    }
    o.push_str(
        "\n// Obligation 3: the schema hash of every pinned type, per instantiation.\n\
         macro_rules! pin {\n    ($t:ty, $h:expr) => {\n        \
         #[cfg(not(feature = \"unpinned\"))]\n        \
         const _: () = assert!(<$t as Snap>::SCHEMA_HASH == $h);\n    };\n}\n",
    );
    for (t, name, hash) in pinned(doc, descs) {
        let Some(h) = hash else {
            errors.push(format!("{name}: its descriptor declares no SCHEMA_HASH"));
            continue;
        };
        if unnameable.contains(name) {
            let _ = writeln!(o, "// `{name}` ({}): in `tests/tables/pins.txt`.", t.pin);
        } else {
            let _ = writeln!(o, "pin!({}, {});", rust_type(name), hex(h));
        }
    }
    if errors.is_empty() { Ok(o) } else { Err(errors) }
}

fn numbers(o: &mut String, m: &str, title: &str, list: &[Number], errors: &mut Vec<String>) {
    let _ = write!(o, "\n/// {title}.\npub(crate) mod {m} {{\n");
    let mut seen = BTreeSet::new();
    for n in list {
        match &n.name {
            Some(name) => {
                let c = screaming(name);
                if !seen.insert(c.clone()) {
                    errors.push(format!("digest-kinds.md:{}: constant `{m}::{c}` twice", n.line));
                }
                let _ = writeln!(o, "    pub(crate) const {c}: u32 = {};", n.value);
            }
            None => {
                let word = if n.reserved { "reserved" } else { "retired" };
                let _ = writeln!(o, "    // {}: {word}.", n.value);
            }
        }
    }
    o.push_str("}\n");
}

fn variant_module(
    o: &mut String,
    t: &Type,
    descs: &Descs,
    unnameable: &BTreeSet<String>,
    errors: &mut Vec<String>,
) {
    // A row function only for an enumeration with a descriptor that Slip
    // can name.
    let desc = (t.kind == Kind::Enum && t.pin != Pin::None)
        .then(|| descs.of(&t.path).next())
        .flatten()
        .filter(|d| d.name == t.path && !unnameable.contains(&d.name));
    o.push_str(if desc.is_some() {
        "    use super::{Decision, Row, kiln};\n\n"
    } else {
        "    use super::{Decision, Row};\n\n"
    });
    let mut seen = BTreeSet::new();
    let mut arms = String::new();
    let path = rust_type(&t.path);
    for r in t.variant_rows() {
        let c = screaming(&r.member);
        if !seen.insert(c.clone()) {
            errors.push(format!(
                "digest-kinds.md:{}: constant `{}::{c}` twice",
                r.line,
                module(&t.short)
            ));
        }
        let tag = match &r.encoding {
            Encoding::As(v) => t.number_of(v),
            _ => t.number_of(&r.member),
        };
        let Some(tag) = tag else {
            errors.push(format!("digest-kinds.md:{}: `{}` has no number", r.line, r.text));
            continue;
        };
        let _ = writeln!(
            o,
            "    pub(crate) const {c}: Row = Row {{ tag: {tag}, decision: Decision::{} }};",
            r.decision.rust()
        );
        if let Some(d) = desc
            && let Some((_, fields)) = d.variants.iter().find(|(v, _)| v == &r.member)
        {
            let pat = match fields.first() {
                None => String::new(),
                Some(f) if f.bytes().all(|b| b.is_ascii_digit()) => "(..)".to_owned(),
                Some(_) => " { .. }".to_owned(),
            };
            let _ = writeln!(arms, "            {path}::{}{pat} => {c},", r.member);
        }
    }
    if desc.is_some() {
        let _ = write!(
            o,
            "\n    pub(crate) fn row(v: &{path}) -> Row {{\n        match v {{\n{arms}        }}\n    }}\n"
        );
    }
}

/// `tests/tables/extra.rs`: the registration of every `pin=extra` type.
pub fn extra_rs(doc: &Doc, unnameable: &BTreeSet<String>) -> String {
    let mut o = String::from(HEADER);
    o.push_str(
        "\n//! The types whose `pin` is `extra` (`spec/digest-kinds.md` §1.1), which\n\
         //! the test registers by name since `Ast`'s descriptor does not reach them.\n\n\
         use slip_kiln::kiln;\n\
         use kiln::snap::{Schema, Snap};\n\n\
         pub fn register(s: &mut Schema) {\n",
    );
    for t in doc.types.iter().filter(|t| t.pin == Pin::Extra) {
        if unnameable.contains(&t.path) {
            let _ = writeln!(o, "    // `{}`: cannot be named from outside Kiln.", t.path);
        } else {
            let _ = writeln!(o, "    <{} as Snap>::schema(s);", rust_type(&t.path));
        }
    }
    o.push_str("}\n");
    o
}

/// The comment `pins.txt` starts with.
pub const PINS_HEADER: &str = "\
# The schema pins of the types `src/tables.rs` cannot name from outside Kiln
# (spec/digest.md §13 obligation 3; WP-023): `<SCHEMA_HASH> <type>`, one per
# line, sorted by type. A type is listed by hand; SLIP_BLESS=1 rewrites the
# hashes. Each line is a visibility request to Kiln.
";

/// `pins.txt` for the listed names, with today's hashes; a listed name
/// that is not a pinned instantiation is an error.
pub fn pins_txt(
    doc: &Doc,
    descs: &Descs,
    unnameable: &BTreeSet<String>,
) -> Result<String, Vec<String>> {
    let pins = pinned(doc, descs);
    let mut o = String::from(PINS_HEADER);
    let mut errors = vec![];
    for name in unnameable {
        match pins.iter().find(|(_, n, _)| n == name) {
            Some((_, _, Some(h))) => {
                let _ = writeln!(o, "{} {name}", hex(*h));
            }
            _ => errors.push(format!("pins.txt: `{name}` is not a pinned type")),
        }
    }
    if errors.is_empty() { Ok(o) } else { Err(errors) }
}

/// The names `pins.txt` lists.
pub fn pins_names(text: &str) -> Result<BTreeSet<String>, Vec<String>> {
    let mut out = BTreeSet::new();
    let mut errors = vec![];
    for (k, line) in text.lines().enumerate() {
        if line.starts_with('#') {
            continue;
        }
        match line.split_once(' ') {
            Some((h, name)) if h.starts_with("0x") && !name.is_empty() => {
                out.insert(name.to_owned());
            }
            _ => errors.push(format!("pins.txt:{}: `{line}` is not `<hash> <type>`", k + 1)),
        }
    }
    if errors.is_empty() { Ok(out) } else { Err(errors) }
}
