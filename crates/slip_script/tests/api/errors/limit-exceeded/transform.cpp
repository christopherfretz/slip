// spec: §4 table limit_exceeded
// `limit_exceeded` (spec/api.md §4, the table): a bound of §7.7. One
// qualified name argument may hold 2^12 bytes: a name of exactly 4096
// bytes is looked up (holding a limit does not exceed it), one of 4097
// bytes throws. The value is 6.
#include <slip/meta.h>

using namespace slip;

consteval std::string num(unsigned long long n) {
  return n < 10 ? std::string(1, static_cast<char>('0' + n))
                : num(n / 10) + static_cast<char>('0' + n % 10);
}

consteval std::string errc_name(errc c) {
  switch (c) {
    case errc::invalid_handle: return "invalid_handle";
    case errc::wrong_kind: return "wrong_kind";
    case errc::invalid_argument: return "invalid_argument";
    case errc::not_editable: return "not_editable";
    case errc::unsupported: return "unsupported";
    case errc::limit_exceeded: return "limit_exceeded";
  }
  return "errc " + num(static_cast<unsigned>(c));
}

// What a call did: "returned", or the errc it threw, its value (§4: the
// enumerators' values are part of the API), and whether it has a message.
#define OUTCOME(...)                                                          \
  [&]() consteval -> std::string {                                            \
    try {                                                                     \
      (void)(__VA_ARGS__);                                                    \
      return "returned";                                                      \
    } catch (const error& e) {                                                \
      return errc_name(e.code()) + " = " + num(static_cast<unsigned>(e.code())) + \
             (e.message().empty() ? ", no message" : ", a message");           \
    }                                                                         \
  }()


consteval void transform() {
  std::string at_limit(4096, 'a');
  std::string over(4097, 'a');
  report(severity::note, "lookup(4096 bytes): " + OUTCOME(lookup(at_limit)));
  report(severity::note, "lookup(4097 bytes): " + OUTCOME(lookup(over)));
}
